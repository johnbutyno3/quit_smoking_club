class MusicItem {
  final String id;
  final String title;
  final String summary;
  final String category;
  final String language;
  final String description;
  final String link;

  const MusicItem({
    required this.id,
    required this.title,
    required this.summary,
    required this.category,
    required this.language,
    required this.description,
    required this.link,
  });
}
